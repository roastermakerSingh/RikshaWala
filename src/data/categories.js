// Each category holds song titles used purely as YouTube search queries
// (see youtube/youtubeSearch.js) — no audio/lyrics are stored here. Titles
// are real, publicly known song names used as factual metadata.

function makeSongs(artist, titles, queryHint = "Bhojpuri song") {
  return titles.map((title, i) => ({
    id: `${artist}-${i + 1}`,
    title,
    artist,
    query: `${artist} ${title} ${queryHint}`,
  }));
}

